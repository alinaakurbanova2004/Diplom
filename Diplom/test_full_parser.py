from src.parser.antlr_parser import AntlrBSLParser

parser = AntlrBSLParser()

# Тест 1: Простые объявления
code1 = """
Перем Счетчик Экспорт;
Перем Временная;

Функция Сложить(А, Б)
    Возврат А + Б;
КонецФункции

Процедура Тест(Парам)
    Сообщить(Парам);
КонецПроцедуры
"""

# Тест 2: Условные операторы
code2 = """
Функция Проверить(Знач Число)
    Если Число > 0 Тогда
        Возврат Истина;
    Иначе
        Возврат Ложь;
    КонецЕсли;
КонецФункции
"""

# Тест 3: Циклы
code3 = """
Процедура Посчитать(Знач N)
    Сумма = 0;
    Для Сч = 1 По N Цикл
        Сумма = Сумма + Сч;
    КонецЦикла;
    Сообщить(Сумма);
КонецПроцедуры
"""

# Тест 4: Сложные выражения
code4 = """
Функция Вычислить(А, Б, В)
    Результат = (А + Б) * В / 2;
    Возврат Результат;
КонецФункции
"""

# Тест 5: Вложенные функции и вызовы
code5 = """
Функция Внутренняя(Х)
    Возврат Х * 2;
КонецФункции

Процедура Внешняя()
    Результат = Внутренняя(5);
    Сообщить(Результат);
КонецПроцедуры
"""

test_cases = [
    ("Простые объявления", code1),
    ("Условные операторы", code2),
    ("Циклы", code3),
    ("Сложные выражения", code4),
    ("Вложенные функции", code5),
]

for name, code in test_cases:
    print(f"\n{'='*60}")
    print(f"🧪 ТЕСТ: {name}")
    print(f"{'='*60}")

    module = parser.parse_string(code, f"{name}.bsl")

    if module:
        print("Успешно!")
        print(f"   Переменных: {len(module.variables)}")
        print(f"   Функций: {len(module.functions)}")
        print(f"   Процедур: {len(module.procedures)}")
        # Вывод параметров функций
        print("Параметры функций:")
        for func in module.functions:
            print(f"   Функция '{func.name}': {len(
                func.parameters)} параметров")
        # Вывод параметров процедур
        print("Параметры процедур:")
        for proc in module.procedures:
            print(f"   Процедура '{proc.name}': {len(
                proc.parameters)} параметров")
    else:
        print("Ошибка парсинга!")
